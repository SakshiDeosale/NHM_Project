import express from "express";
import multer from "multer";
import bcrypt from "bcrypt";
import { randomUUID } from "node:crypto";
import { getPool, sql } from "../config/db.js";
import { authenticateToken } from "../middleware/authMiddleware.js";

const router = express.Router();
router.use(authenticateToken);

const upload = multer({
    storage: multer.memoryStorage(),
    limits: { fileSize: 2 * 1024 * 1024 },
    fileFilter: (req, file, cb) => {
        const allowedTypes = [
            "image/jpeg",
            "image/png",
            "image/webp",
        ];

        if (allowedTypes.includes(file.mimetype)) {
            cb(null, true);
        } else {
            cb(new Error("Only JPG, PNG, and WebP images are allowed."));
        }
    },
});

// Generate username: Designation + CircleName + UserID
function generateUsername(designation, circleName, userID) {
    const designationCode = designation.replace(/[^a-zA-Z0-9]/g, "");
    const circleCode = circleName.replace(/[^a-zA-Z0-9]/g, "");

    return `${designationCode}${circleCode}${userID}`;
}

// Validate user fields
function validateUser({
    surname,
    firstName,
    middleName,
    mobile,
    email,
    designation,
    circle,
    district,
}) {
    if (
        !surname?.trim() ||
        !firstName?.trim() ||
        !middleName?.trim() ||
        !mobile ||
        !email?.trim() ||
        !designation?.trim() ||
        !circle?.trim() ||
        !district?.trim()
    ) {
        return "Please fill in all required fields.";
    }

    if (!/^[6-9][0-9]{9}$/.test(mobile)) {
        return "Enter a valid 10-digit mobile number.";
    }

    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email.trim())) {
        return "Enter a valid email address.";
    }

    return null;
}

// GET: Display active users
router.get("/", async (req, res) => {
    try {
        const pool = await getPool();

        const result = await pool.request().query(`
      SELECT
        UserID,
        Surname,
        FirstName,
        MiddleName,
        Mobile,
        Email,
        Designation,
        Circle,
        District,
        Username,
        IsActive,
        CASE
          WHEN PhotoData IS NOT NULL THEN 1
          ELSE 0
        END AS HasPhoto,
        CreatedAt
      FROM dbo.Users
      WHERE IsActive = 1
      ORDER BY UserID DESC;
    `);

        // Never return PasswordHash to the frontend.
        res.json(result.recordset);
    } catch (error) {
        console.error("Fetch users error:", error.message);
        res.status(500).json({
            message: "Unable to fetch users.",
        });
    }
});

// POST: Add a user
router.post("/", upload.single("photo"), async (req, res) => {
    let transaction;

    try {
        const {
            surname,
            firstName,
            middleName,
            mobile,
            email,
            designation,
            circle,
            district,
        } = req.body;

        const validationError = validateUser({
            surname,
            firstName,
            middleName,
            mobile,
            email,
            designation,
            circle,
            district,
        });

        if (validationError) {
            return res.status(400).json({
                message: validationError,
            });
        }

        // The mobile number is the initial password.
        // Store only its bcrypt hash.
        const passwordHash = mobile;

        const pool = await getPool();
        transaction = new sql.Transaction(pool);
        await transaction.begin();

        // Use a temporary unique username because UserID is
        // generated by SQL Server during insertion.
        const temporaryUsername = `TEMP_${randomUUID()}`;

        const insertResult = await new sql.Request(transaction)
            .input("Surname", sql.NVarChar(100), surname.trim())
            .input("FirstName", sql.NVarChar(100), firstName.trim())
            .input("MiddleName", sql.NVarChar(100), middleName.trim())
            .input("Mobile", sql.NVarChar(10), mobile)
            .input("Email", sql.NVarChar(255), email.trim())
            .input("Designation", sql.NVarChar(100), designation.trim())
            .input("Circle", sql.NVarChar(100), circle.trim())
            .input("District", sql.NVarChar(100), district.trim())
            .input("Username", sql.NVarChar(100), temporaryUsername)
            .input("PasswordHash", sql.NVarChar(255), passwordHash)
            .input(
                "PhotoData",
                sql.VarBinary(sql.MAX),
                req.file ? req.file.buffer : null
            )
            .query(`
        INSERT INTO dbo.Users (
          Surname,
          FirstName,
          MiddleName,
          Mobile,
          Email,
          Designation,
          Circle,
          District,
          Username,
          PasswordHash,
          PhotoData
        )
        OUTPUT INSERTED.UserID
        VALUES (
          @Surname,
          @FirstName,
          @MiddleName,
          @Mobile,
          @Email,
          @Designation,
          @Circle,
          @District,
          @Username,
          @PasswordHash,
          @PhotoData
        );
      `);

        const userID = insertResult.recordset[0].UserID;

        // Generate the final username using the actual database UserID.
        const username = generateUsername(
            designation.trim(),
            circle.trim(),
            userID
        );

        await new sql.Request(transaction)
            .input("UserID", sql.Int, userID)
            .input("Username", sql.NVarChar(100), username)
            .query(`
        UPDATE dbo.Users
        SET Username = @Username
        WHERE UserID = @UserID;
      `);

        await transaction.commit();
        transaction = null;

        res.status(201).json({
            message: "User added successfully.",
            userID,
            username,
        });
    } catch (error) {
        if (transaction) {
            try {
                await transaction.rollback();
            } catch (rollbackError) {
                console.error("Transaction rollback error:", rollbackError.message);
            }
        }

        console.error("Create user error:", error.message);

        if (error.number === 2627 || error.number === 2601) {
            return res.status(409).json({
                message: "A mobile number, email, or username already exists.",
            });
        }

        res.status(500).json({
            message: "Unable to add user.",
        });
    }
});

// PUT: Edit an existing user
router.put("/:id", upload.single("photo"), async (req, res) => {
    try {
        const userID = Number(req.params.id);

        if (!Number.isInteger(userID) || userID <= 0) {
            return res.status(400).json({
                message: "Invalid user ID.",
            });
        }

        const {
            surname,
            firstName,
            middleName,
            mobile,
            email,
            designation,
            circle,
            district,
        } = req.body;

        const validationError = validateUser({
            surname,
            firstName,
            middleName,
            mobile,
            email,
            designation,
            circle,
            district,
        });

        if (validationError) {
            return res.status(400).json({
                message: validationError,
            });
        }

        const pool = await getPool();

        // Keep the same UserID suffix when editing.
        const username = generateUsername(
            designation.trim(),
            circle.trim(),
            userID
        );

        const request = pool.request()
            .input("UserID", sql.Int, userID)
            .input("Surname", sql.NVarChar(100), surname.trim())
            .input("FirstName", sql.NVarChar(100), firstName.trim())
            .input("MiddleName", sql.NVarChar(100), middleName.trim())
            .input("Mobile", sql.NVarChar(10), mobile)
            .input("Email", sql.NVarChar(255), email.trim())
            .input("Designation", sql.NVarChar(100), designation.trim())
            .input("Circle", sql.NVarChar(100), circle.trim())
            .input("District", sql.NVarChar(100), district.trim())
            .input("Username", sql.NVarChar(100), username)
            .input(
                "PhotoData",
                sql.VarBinary(sql.MAX),
                req.file ? req.file.buffer : null
            );

        const result = await request.query(`
      UPDATE dbo.Users
      SET
        Surname = @Surname,
        FirstName = @FirstName,
        MiddleName = @MiddleName,
        Mobile = @Mobile,
        Email = @Email,
        Designation = @Designation,
        Circle = @Circle,
        District = @District,
        Username = @Username,
        PhotoData = COALESCE(@PhotoData, PhotoData)
      WHERE UserID = @UserID
        AND IsActive = 1;

      SELECT @@ROWCOUNT AS RowsAffected;
    `);

        if (result.recordset[0].RowsAffected === 0) {
            return res.status(404).json({
                message: "User not found.",
            });
        }

        res.json({
            message: "User updated successfully.",
            username,
        });
    } catch (error) {
        console.error("Update user error:", error.message);

        if (error.number === 2627 || error.number === 2601) {
            return res.status(409).json({
                message: "A mobile number, email, or username already exists.",
            });
        }

        res.status(500).json({
            message: "Unable to update user.",
        });
    }
});

// GET: Retrieve a user's photo
router.get("/:id/photo", async (req, res) => {
    try {
        const userID = Number(req.params.id);

        if (!Number.isInteger(userID) || userID <= 0) {
            return res.status(400).send("Invalid user ID.");
        }

        const pool = await getPool();

        const result = await pool.request()
            .input("UserID", sql.Int, userID)
            .query(`
        SELECT PhotoData
        FROM dbo.Users
        WHERE UserID = @UserID
          AND IsActive = 1;
      `);

        if (
            result.recordset.length === 0 ||
            !result.recordset[0].PhotoData
        ) {
            return res.status(404).send("Photo not found.");
        }

        // This matches JPEG uploads. PNG/WebP need their content
        // type stored separately to be served with the correct type.
        res.set("Content-Type", "image/jpeg");
        res.set("Cache-Control", "no-store");
        res.send(result.recordset[0].PhotoData);
    } catch (error) {
        console.error("Fetch photo error:", error.message);
        res.status(500).send("Unable to retrieve photo.");
    }
});

